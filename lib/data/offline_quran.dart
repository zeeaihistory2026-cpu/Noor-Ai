import 'dart:convert';
import 'package:archive/archive.dart';
import 'package:flutter/foundation.dart';
import 'package:flutter/services.dart';

Map<String, dynamic> _decodeQuran(Uint8List bytes) =>
    jsonDecode(utf8.decode(const GZipDecoder().decodeBytes(bytes)))
        as Map<String, dynamic>;

class OfflineQuranMatch {
  const OfflineQuranMatch({
    required this.surah,
    required this.surahName,
    required this.ayah,
    required this.arabicText,
    required this.translationText,
  });

  final int surah;
  final String surahName;
  final int ayah;
  final String arabicText;
  final String translationText;

  String get reference => 'Quran $surah:$ayah';
}

/// Source downloads are validated by tool/bundle_quran_content.py before
/// shipping. No verse text or pagination is generated by the app.
abstract final class OfflineQuran {
  static final Map<String, Future<Map<String, dynamic>>> _loads = {};
  static Future<Map<String, dynamic>> load(String edition) =>
      _loads.putIfAbsent(edition, () async {
        final bytes = await rootBundle.load('assets/quran/$edition.json.gz');
        return compute(_decodeQuran, bytes.buffer.asUint8List());
      });

  static Future<Map<String, dynamic>> surah(int number, String edition) async {
    final data = await load(edition);
    final surahs = data['surahs'] as List;
    return Map<String, dynamic>.from(
        surahs.firstWhere((s) => s['number'] == number) as Map);
  }

  static Future<Map<String, dynamic>> mushafPage(int page) async =>
      Map<String, dynamic>.from((await load('mushaf16'))['$page'] as Map);

  static Future<int> pageForSurah(int surah) => pageForVerse(surah, 1);

  static Future<int> pageForVerse(int surah, int ayah) async {
    final pages = await load('mushaf16');
    for (int page = 1; page <= 548; page++) {
      if ((pages['$page']['verses'] as List)
          .any((v) => v['verse_key'] == '$surah:$ayah')) {
        return page;
      }
    }
    throw StateError('Surah not found');
  }

  static Future<int> pageForJuz(int juz) async {
    final pages = await load('mushaf16');
    for (int page = 1; page <= 548; page++) {
      if ((pages['$page']['verses'] as List)
          .any((v) => v['juz_number'] == juz)) {
        return page;
      }
    }
    throw StateError('Juz not found');
  }

  static const _bismillahA =
      '\u0628\u0650\u0633\u0652\u0645\u0650 \u0671\u0644\u0644\u0651\u064e\u0647\u0650 \u0671\u0644\u0631\u0651\u064e\u062d\u0652\u0645\u064e\u0670\u0646\u0650 \u0671\u0644\u0631\u0651\u064e\u062d\u0650\u064a\u0645\u0650 ';
  static const _bismillahB =
      '\u0628\u0651\u0650\u0633\u0652\u0645\u0650 \u0671\u0644\u0644\u0651\u064e\u0647\u0650 \u0671\u0644\u0631\u0651\u064e\u062d\u0652\u0645\u064e\u0670\u0646\u0650 \u0671\u0644\u0631\u0651\u064e\u062d\u0650\u064a\u0645\u0650 ';

  static const _normBismillahPrefix =
      '\u0628\u0633\u0645 \u0627\u0644\u0644\u0647 \u0627\u0644\u0631\u062d\u0645\u0646 \u0627\u0644\u0631\u062d\u064a\u0645';

  /// Separates the leading Bismillah prepended to Ayah 1 in Uthmani editions
  /// for Surahs 2..114 (excluding At-Tawbah, Surah 9).
  static String stripLeadingBismillah(int surah, int ayah, String text) {
    var clean = text.replaceFirst('\ufeff', '').trimLeft();
    if (surah != 1 && surah != 9 && ayah == 1) {
      if (clean.startsWith(_bismillahA)) {
        return clean.substring(_bismillahA.length).trimLeft();
      }
      if (clean.startsWith(_bismillahB)) {
        return clean.substring(_bismillahB.length).trimLeft();
      }
      final fourWords = RegExp(r'^\S+\s+\S+\s+\S+\s+\S+\s+').firstMatch(clean);
      if (fourWords != null &&
          normalizeArabic(clean.substring(0, fourWords.end)) ==
              _normBismillahPrefix) {
        return clean.substring(fourWords.end).trimLeft();
      }
    }
    return clean;
  }

  /// Strips Arabic harakat/diacritics and normalizes Alef/Teh/Alef-Maksura
  /// so offline Arabic keyword queries match naturally.
  static String normalizeArabic(String input) {
    final withoutDiacritics = input.replaceAll(
        RegExp(r'[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\ufeff]'), '');
    return withoutDiacritics
        .replaceAll(RegExp(r'[\u0622\u0623\u0625\u0671]'), '\u0627')
        .replaceAll('\u0629', '\u0647')
        .replaceAll('\u0649', '\u064a')
        .trim();
  }

  /// Searches all 6,236 bundled ayahs offline across English, Urdu, or Arabic.
  static Future<List<OfflineQuranMatch>> search(
    String query, {
    String translationEdition = 'en.sahih',
    int limit = 30,
  }) async {
    final trimmed = query.trim();
    if (trimmed.isEmpty) return const [];

    final arData = await load('quran-uthmani');
    final trData = await load(translationEdition);
    final arSurahs = arData['surahs'] as List;
    final trSurahs = trData['surahs'] as List;

    final isArabicQuery = RegExp(r'[\u0600-\u06FF]').hasMatch(trimmed);
    final normQuery =
        isArabicQuery ? normalizeArabic(trimmed) : trimmed.toLowerCase();

    // Direct "surah:ayah" jump support (e.g., "2:255" or "18:10").
    final refMatch = RegExp(r'^(\d{1,3})\s*:\s*(\d{1,3})$').firstMatch(trimmed);
    if (refMatch != null) {
      final sNum = int.tryParse(refMatch.group(1)!);
      final aNum = int.tryParse(refMatch.group(2)!);
      if (sNum != null && sNum >= 1 && sNum <= 114 && aNum != null && aNum >= 1) {
        final arSurah = arSurahs[sNum - 1] as Map;
        final trSurah = trSurahs[sNum - 1] as Map;
        final arAyahs = arSurah['ayahs'] as List;
        final trAyahs = trSurah['ayahs'] as List;
        if (aNum <= arAyahs.length) {
          final arText = stripLeadingBismillah(
              sNum, aNum, (arAyahs[aNum - 1]['text'] ?? '').toString());
          final trText = (trAyahs[aNum - 1]['text'] ?? '').toString();
          return [
            OfflineQuranMatch(
              surah: sNum,
              surahName: (arSurah['englishName'] ?? 'Surah $sNum').toString(),
              ayah: aNum,
              arabicText: arText,
              translationText: trText,
            ),
          ];
        }
      }
    }

    final matches = <OfflineQuranMatch>[];
    for (var i = 0; i < arSurahs.length && matches.length < limit; i++) {
      final arSurah = arSurahs[i] as Map;
      final trSurah = trSurahs[i] as Map;
      final sNum = (arSurah['number'] as num).toInt();
      final sName = (arSurah['englishName'] ?? 'Surah $sNum').toString();
      final arAyahs = arSurah['ayahs'] as List;
      final trAyahs = trSurah['ayahs'] as List;
      for (var j = 0; j < arAyahs.length && matches.length < limit; j++) {
        final aNum = (arAyahs[j]['numberInSurah'] as num?)?.toInt() ?? (j + 1);
        final rawAr = (arAyahs[j]['text'] ?? '').toString();
        final arText = stripLeadingBismillah(sNum, aNum, rawAr);
        final trText =
            j < trAyahs.length ? (trAyahs[j]['text'] ?? '').toString() : '';

        final hit = isArabicQuery
            ? (normalizeArabic(arText).contains(normQuery) ||
                normalizeArabic(trText).contains(normQuery))
            : trText.toLowerCase().contains(normQuery);

        if (hit) {
          matches.add(OfflineQuranMatch(
            surah: sNum,
            surahName: sName,
            ayah: aNum,
            arabicText: arText,
            translationText: trText,
          ));
        }
      }
    }
    return matches;
  }
}
